HEADER = '''# GENERATED by tools/qwen38_oneshot_wiring_gen.py -- do not edit by hand.
#
# vLLM's CudaCommunicator, {version}, stock sha256 {sha},
# plus the one-shot AllReduce hook (tp_oneshot_ar's shim); see the generator.
'''


def generate(stock_text: str) -> str:
    digest = hashlib.sha256(stock_text.encode()).hexdigest()
    if digest != STOCK_SHA256:
        raise SystemExit(
            f"ABORT: stock cuda_communicator.py is {digest[:16]}..., not the pinned "
            f"{STOCK_SHA256[:16]}... ({STOCK_VERSION}); re-read the hook site first.")
    text = stock_text
    for name, old, new in EDITS:
        n = text.count(old)
        if n != 1:
            raise SystemExit(f"ABORT: anchor for '{name}' occurs {n} times, not once")
        text = text.replace(old, new, 1)
    return HEADER.format(version=STOCK_VERSION, sha=STOCK_SHA256) + text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--stock", required=True)
    ap.add_argument("--out")
    ap.add_argument("--check")
    args = ap.parse_args()
    out = generate(Path(args.stock).read_text())
    if args.check:
        if Path(args.check).read_text() != out:
            print(f"MISMATCH: {args.check} is not stock + the pinned edit"); return 1
        print(f"OK: {args.check} == stock {STOCK_SHA256[:16]}... + {len(EDITS)} edit")
    if args.out:
        Path(args.out).write_text(out); print(f"wrote {args.out} ({len(out.splitlines())} lines)")
    if not args.out and not args.check:
        sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
