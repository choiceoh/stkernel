#!/usr/bin/env python3
"""Generate the Qwen3.8 image's one-shot AllReduce wiring: stock + the hook.

`tp_oneshot_ar` is the portable half -- the host-register RDMA one-shot
AllReduce kernel and its shim (27 us against NCCL's 67 us for small decode
tensors on this fabric; GLM-5.3 serves with `VLLM_DSV4_ONESHOT_AR=1`). The
other half hooks `CudaCommunicator.all_reduce`, and that file is the image's:
`dsv4_oneshot_wiring` carries it for the ds4 image, this generator writes it
for `qwen38-fi618:local` (vLLM v0.1.dev20073) from that image's stock file.

One edit: the stock `all_reduce` becomes `_all_reduce_impl` and a wrapper
named `all_reduce` tries the one-shot path first -- pre-commit failures fall
back to NCCL after the shim's all-rank vote, post-commit faults propagate
(a rank-local fallback would split the collective and deadlock the others).
Text identical to the ds4 wiring's block; only the file around it differs.

    python3 tools/qwen38_oneshot_wiring_gen.py --stock <image>/cuda_communicator.py \\
        --out overlay/modules/qwen38_oneshot_wiring/cuda_communicator.py
    python3 tools/qwen38_oneshot_wiring_gen.py --stock ... --check <committed file>
"""

